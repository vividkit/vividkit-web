export interface AkSkillEntry {
  id: string;
  command: string;
  commandCodex: string;
  description: string;
  descriptionVi?: string;
  /** Workflow/GTM group key (UI section) — not SKILL.md metadata */
  category: AkSkillGroupKey;
  /** Full argument-hint from SKILL.md frontmatter */
  argumentHint?: string;
  /** Colon/space skill branches, e.g. archive, cm, ui */
  subcommands?: string[];
  /** Positional / placeholder args, e.g. [task], <PR number or URL> */
  args?: string[];
  /** Dash flags, e.g. --fast, --parallel */
  flags?: string[];
  /** Dual-list with Beta Preview (CK convention) */
  isBeta?: boolean;
  /** Emerald NEW badge on cheatsheet cards — distinct from isBeta */
  isNew?: boolean;
  /** Ordered essentials path (1-based) */
  step?: number;
  /** Unnumbered essentials rank after step (lower first) */
  order?: number;
}

